if (still) {
  document.querySelectorAll('.reveal').forEach(el => el.classList.add('in'));
} else {
  const io = new IntersectionObserver(es => es.forEach(e => {
    if (e.isIntersecting) { e.target.classList.add('in'); io.unobserve(e.target); }
  }), { threshold: 0.12 });
  document.querySelectorAll('.reveal').forEach(el => io.observe(el));

  const items = [...document.querySelectorAll('[data-rot],[data-speed]')].map(el => ({
    el, host: el.closest('.card, .hero-stage'),
    y: 0, a: 0, ty: 0, ta: 0
  }));
  let running = false;

  const aim = () => {
    const vh = innerHeight;
    items.forEach(i => {
      const r = i.host.getBoundingClientRect();
      const p = Math.max(-1.2, Math.min(1.2, (r.top + r.height / 2 - vh / 2) / vh));
      i.ty = (+i.el.dataset.speed || 0) * p;
      i.ta = (+i.el.dataset.rot || 0) * p;
    });
    if (!running) { running = true; requestAnimationFrame(step); }
  };

  const step = () => {
    let moving = false;
    items.forEach(i => {
      i.y += (i.ty - i.y) * 0.075;
      i.a += (i.ta - i.a) * 0.075;
      if (Math.abs(i.ty - i.y) > 0.05 || Math.abs(i.ta - i.a) > 0.01) moving = true;
      i.el.style.transform = `translate3d(0,${i.y.toFixed(2)}px,0) rotate(${i.a.toFixed(3)}deg)`;
    });
    if (moving) requestAnimationFrame(step); else running = false;
  };

  addEventListener('scroll', aim, { passive: true });
  addEventListener('resize', aim);
  aim();
}

