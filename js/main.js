const still = matchMedia('(prefers-reduced-motion: reduce)').matches;
const st = document.querySelector('.statement');
const langs = Object.keys(T);
const bar = document.querySelector('.lang');

function paint() {
  const w = st.querySelectorAll('span');
  if (still) { w.forEach(s => s.classList.add('on')); return; }
  const r = st.getBoundingClientRect();
  const p = Math.max(0, Math.min(1, (innerHeight * 0.85 - r.top) / (r.height + innerHeight * 0.3)));
  const n = Math.round(p * w.length);
  w.forEach((s, i) => s.classList.toggle('on', i < n));
}

function setLang(l) {
  document.documentElement.lang = l;
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = T[l][el.dataset.i18n]; });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => el.setAttribute('aria-label', T[l][el.dataset.i18nAria]));
  st.innerHTML = T[l].st_h.split(' ').map(w => '<span>' + w + '</span>').join(' ');
  paint();
  bar.style.setProperty('--i', langs.indexOf(l));
  bar.querySelectorAll('button').forEach(b => b.setAttribute('aria-pressed', b.dataset.lang === l));
}
bar.addEventListener('click', e => { const b = e.target.closest('button'); if (b) setLang(b.dataset.lang); });
setLang('en');
